// Every tag the reference enumerates: the registered features plus the numbered sets.
export const ALL_OPENTYPE_TAGS: string[] = [
    ...Object.keys(OPENTYPE_FEATURES),
    ...Array.from({ length: 20 }, (_, i) => `ss${String(i + 1).padStart(2, "0")}`),
    ...Array.from({ length: 99 }, (_, i) => `cv${String(i + 1).padStart(2, "0")}`),
];

export function featureName(tag: string): string {
    if (/^ss\d\d$/.test(tag)) return `Stylistic set ${Number(tag.slice(2))}`;
    if (/^cv\d\d$/.test(tag)) return `Character variant ${Number(tag.slice(2))}`;
    return OPENTYPE_FEATURES[tag] ?? tag.toUpperCase();
}
